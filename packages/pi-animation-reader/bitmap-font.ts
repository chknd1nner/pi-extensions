export function hasGlyph(ch: string): boolean {
  return ch in GLYPHS || ch.toUpperCase() in GLYPHS;
}

export function glyphHeightFor(cellWidth: number): number {
  return Math.max(10, Math.min(24, Math.round(cellWidth / 8)));
}

function putPixel(canvas: Uint8Array, w: number, h: number, x: number, y: number, rgb: [number, number, number]): void {
  if (x < 0 || y < 0 || x >= w || y >= h) return;
  const o = (y * w + x) * 4;
  canvas[o] = rgb[0];
  canvas[o + 1] = rgb[1];
  canvas[o + 2] = rgb[2];
  canvas[o + 3] = 255;
}

/** Draw text with a 1px-scaled outline box behind it for contrast. Returns drawn width. */
export function drawText(
  canvas: Uint8Array,
  canvasW: number,
  canvasH: number,
  x: number,
  y: number,
  text: string,
  glyphH: number,
  color: [number, number, number] = [255, 255, 255],
): number {
  const scale = Math.max(1, Math.floor(glyphH / 7));
  const glyphW = 5 * scale;
  const advance = glyphW + scale;
  const textW = text.length * advance - scale;
  const textH = 7 * scale;

  // contrast plate
  for (let py = y - scale; py <= y + textH; py++) {
    for (let px = x - scale; px <= x + textW; px++) {
      putPixel(canvas, canvasW, canvasH, px, py, [16, 16, 16]);
    }
  }

  let cursor = x;
  for (const ch of text.toUpperCase()) {
    const glyph = GLYPHS[ch] ?? GLYPHS["?"] ?? GLYPHS[" "];
    for (let gy = 0; gy < 7; gy++) {
      for (let gx = 0; gx < 5; gx++) {
        if (glyph[gy][gx] !== "1") continue;
        for (let sy = 0; sy < scale; sy++) {
          for (let sx = 0; sx < scale; sx++) {
            putPixel(canvas, canvasW, canvasH, cursor + gx * scale + sx, y + gy * scale + sy, color);
          }
        }
      }
    }
    cursor += advance;
  }
  return cursor - x;
}
